   protected void registerGoals() {
      super.registerGoals();
      this.goalSelector.addGoal(1, new Goal() {
         {
            this.setFlags(EnumSet.of(Flag.MOVE));
         }

         public boolean canUse() {
            return LuxEntity.this.getTarget() != null && !LuxEntity.this.getMoveControl().hasWanted();
         }

         public boolean canContinueToUse() {
            return LuxEntity.this.getMoveControl().hasWanted() && LuxEntity.this.getTarget() != null && LuxEntity.this.getTarget().isAlive();
         }

         public void start() {
            LivingEntity livingentity = LuxEntity.this.getTarget();
            Vec3 vec3d = livingentity.getEyePosition(1.0F);
            LuxEntity.this.moveControl.setWantedPosition(vec3d.x, vec3d.y, vec3d.z, 1.0);
         }

         public void tick() {
            LivingEntity livingentity = LuxEntity.this.getTarget();
            if (LuxEntity.this.getBoundingBox().intersects(livingentity.getBoundingBox())) {
               LuxEntity.this.doHurtTarget(livingentity);
            } else {
               double d0 = LuxEntity.this.distanceToSqr(livingentity);
               if (d0 < 16.0) {
                  Vec3 vec3d = livingentity.getEyePosition(1.0F);
                  LuxEntity.this.moveControl.setWantedPosition(vec3d.x, vec3d.y, vec3d.z, 1.0);
               }
            }
         }
      });
      this.targetSelector.addGoal(2, new HurtByTargetGoal(this, new Class[0]));
   }

